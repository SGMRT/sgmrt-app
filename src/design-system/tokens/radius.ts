// Ghost Runner Design System - Sizing Tokens

// Border Radius
//
// 모서리는 면의 크기가 아니라 **깊이**를 따른다.
// 면 색이 uiBackground -> ui01 -> uiUp 으로 쌓이는 것과 같은 구조다.
// 무엇에 감싸여 있는지를 먼저 보고, 그 다음에 크기로 깎는다.
//
// 1. 원이나 알약이면 `full` 이다.
//    아바타, 표식 점, 토글, 라디오, 바텀시트 손잡이, 토스트가 여기 든다.
//    `100`, `999`, `SIZE / 2` 처럼 직접 계산해도 결과는 같지만,
//    읽는 사람이 왜 다른지 찾게 되므로 `full` 하나만 쓴다.
//
// 2. 화면 아래에서 올라오는 면은 `2xl` 20 이다.
//    바텀시트와 탭 바가 여기 든다. 화면 자체의 가장자리를 대신하는 면이라
//    그 안에 담기는 것들보다 한 단계 크다. 이 값을 쓰는 것은 이 셋뿐이다.
//
// 3. 배경 위에 직접 놓인 면은 `base` 12 다. 이것이 1차 라운드다.
//    카드, 감싸지지 않은 버튼과 입력, 목록의 썸네일이 여기 든다.
//    한 줄짜리 카드와 열 줄짜리 카드가 같은 값을 쓴다.
//    카드의 모서리는 제 높이가 아니라 배경과 맞닿는 자리로 읽히기 때문이다.
//
// 4. 그 면 안에 놓이면 `md` 8 이다.
//    카드 안의 조작, 칩, 배지, 썸네일 위의 표식이 여기 든다.
//    1차와 같은 12 를 쓰면 두 층이 붙어 어느 것이 안쪽인지 알 수 없다.
//
// 5. 또 그 안에 놓이면 `sm` 6 이다. 체크 칸, 차트 막대 머리, 작은 표식이다.
//
// 6. 선과 그보다 얇은 것은 `xs` 4 다.
//
// 크기로 깎기
// -----------
// 깊이가 값을 정하고, 면이 작으면 거기서 내린다.
// 작은 면에 큰 모서리를 주면 알약으로 뭉개져 무슨 모양인지 알 수 없게 된다.
// 짧은 변이 36 미만이면 8, 25 미만이면 6, 13 미만이면 4 를 넘지 않는다.
// 34 짜리 칩이 배경 위에 있어도 12 가 아니라 8 인 것이 이 때문이다.
//
// 겹쳐 앉은 면
// -----------
// 면이 면 안에 4~12 정도로 바짝 붙어 앉으면 바깥에서 사이 여백을 뺀다.
// 썸네일(12) 안에 4 들어와 앉는 고스티 표식은 12 - 4 = 8 이고,
// 마침 4번 규칙이 주는 값과 같다. 지금 앱에서 두 계산이 어긋나는 자리는 없다.
//
// **조작에는 쓰지 않는다.** 버튼은 면이 아니라 손댈 것이라
// 제 깊이에 맞는 모서리를 가져야 버튼으로 읽힌다.
// 카드 구석 가까이 있다는 이유로 값을 내리면
// 둥근 카드 안에 각진 버튼이 놓여 어색해진다.
// 마이페이지 케이던스의 단계 버튼을 이 계산으로 4 까지 내렸다가
// 어색해서 제 깊이값인 8 로 되돌렸다.
//
// 예외는 하나뿐이다
// -----------
// `Button` 은 제 사다리를 가진다. small 8 · medium 12 · large 12 다.
// small 이 높이 24 인데도 6 이 아니라 8 인 것은 이 사다리 때문이다.
// medium 과 large 가 같은 값인 것은 둘 다 배경 위에 놓이기 때문이고,
// 위계는 모서리가 아니라 높이와 색이 나타낸다.
//
// `lg`(14), `xl`(16), `3xl`(24)은 지금 쓰이는 곳이 없다.
// 피그마 Foundation 과 값을 맞춰 두려고 남긴 것이지 고를 자리가 있어서가 아니다.
export const radius = {
    xs: 4,
    sm: 6,
    md: 8,
    base: 12,
    lg: 14,
    xl: 16,
    "2xl": 20,
    "3xl": 24,
    full: 9999,
} as const;

// Type exports
export type Radius = keyof typeof radius;

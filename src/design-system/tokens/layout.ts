// Ghost Runner Design System - Layout Tokens
//
// 화면을 짜는 값 중, 스케일에서 고르는 것이 아니라 "이 앱은 이렇게 짠다" 로
// 한 번 정해 두고 어디서나 같이 쓰는 것들이다.
//
// 간격 스케일(spacing)은 "얼마나 띄울까" 를 고르는 사다리이고,
// 여기 있는 값은 "어디를 띄우는가" 에 이름을 붙인 것이다.
// 같은 16 이라도 화면 가장자리 여백과 아이콘 옆 간격은 뜻이 다르므로,
// 한쪽을 고칠 때 다른 쪽이 따라가면 안 된다.

import { spacing } from "./spacing";

/**
 * 화면 가장자리와 내용 사이의 여백.
 *
 * 헤더, 목록, 화면 아래 버튼이 모두 이 값으로 세로줄을 맞춘다.
 * 예전에는 곳곳에 16.5 가 적혀 있었다. 스케일 밖 값인 데다
 * 화면마다 따로 적혀 있어 한 곳을 고쳐도 나머지가 따라오지 않았다.
 */
export const screenGutter = spacing[16];

/**
 * 섹션(카드)끼리 쌓일 때의 간격.
 *
 * 각 섹션이 사방 20 을 가지므로 사이까지 20 을 두면
 * 가장자리 여백이 두 번 겹쳐 섹션이 서로 멀어진다.
 */
export const sectionGap = spacing[12];

/**
 * 섹션 안쪽 여백이자 줄 사이 간격.
 *
 * 여백은 줄이 아니라 섹션이 갖는다. 줄마다 패딩을 두면
 * 가장자리 여백과 줄 사이 간격이 따로 놀아 한쪽만 고쳐진다.
 */
export const sectionPadding = spacing[20];
